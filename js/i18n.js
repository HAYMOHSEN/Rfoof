export const LANGS = { en, ar };
let current = 'en';

export function detectLang() {
  const saved = localStorage.getItem('rfoof.lang');
  if (saved && LANGS[saved]) return saved;
  return (navigator.language || 'en').toLowerCase().startsWith('ar') ? 'ar' : 'en';
}

export function setLang(l, { silent = false } = {}) {
  if (!LANGS[l]) l = 'en';
  current = l;
  localStorage.setItem('rfoof.lang', l);
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
  if (!silent) i18nEvents.emit('change', l);
}
export const getLang = () => current;
export const isRTL = () => current === 'ar';
export const locale = () => (current === 'ar' ? 'ar-JO-u-nu-latn' : 'en-US');

export function t(key, params) {
  let s = LANGS[current][key] ?? LANGS.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function fmtDate(ts, opts = { dateStyle: 'medium' }) {
  if (!ts) return '—';
  try { return new Intl.DateTimeFormat(locale(), opts).format(new Date(ts)); } catch { return new Date(ts).toLocaleDateString(); }
}
export function fmtDateTime(ts) { return fmtDate(ts, { dateStyle: 'medium', timeStyle: 'short' }); }
export function fmtNum(n) { return new Intl.NumberFormat(locale()).format(n); }
